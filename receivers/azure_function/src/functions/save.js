/*
 * ============================================================================
 *  save.js — the data receiver (Azure Function → Azure Blob Storage)
 * ============================================================================
 *
 *  WHAT IT DOES (in plain words)
 *  -----------------------------
 *  The experiment running in a participant's browser sends ("POSTs") one
 *  participant JSON file at a time to this function's web address. This
 *  function:
 *
 *    1. reads the file text exactly as it arrived,
 *    2. checks that it is a JSON file whose "upload" section says
 *         folder    = "complete", "progress" or "quit"
 *         file_name = something like  P3K9X2QA__AB12CD34__p03_stroop-baseline.json
 *    3. saves the text, unchanged, as
 *         <container>/<folder>/<file_name>
 *       in your Azure Storage account (container "participant-data" unless
 *       you set CONTAINER_NAME), and
 *    4. answers the browser:
 *         200 {"ok":true}   saved
 *         409               a file with that name already exists (this only
 *                           happens when an earlier try of the SAME upload was
 *                           saved but its reply got lost — the browser treats
 *                           409 as "already saved", which is correct)
 *         400 / 413         the request was not a valid participant file
 *         500               storage problem (the browser will try again)
 *
 *  It NEVER overwrites a file: every upload has a unique file name, and the
 *  save uses "only if this file does not exist yet".
 *
 *  Every answer carries the header  Access-Control-Allow-Origin: *  —
 *  without it the browser is not allowed to read the answer and would treat
 *  the upload as failed.
 *
 *  SETTINGS (Azure Portal → your Function App → Settings → Environment
 *  variables → App settings). You do NOT edit this file for these:
 *
 *    DATA_STORAGE_CONNECTION   connection string of the storage account that
 *                              should hold the data (Storage account →
 *                              Security + networking → Access keys →
 *                              Connection string). Recommended.
 *                              If missing, the Function App's own
 *                              AzureWebJobsStorage connection string is used
 *                              (only if it is a classic connection string).
 *    CONTAINER_NAME            optional; default "participant-data". Created
 *                              automatically on first use if it is missing.
 *
 *  WHEN WOULD YOU EDIT THIS FILE?
 *  ------------------------------
 *  Almost never. The only things you might change are in the block marked
 *  "── EDIT HERE ──" just below (size limit, allowed folders, file-name rule).
 *  If the experiment ever starts using a NEW folder name (besides complete /
 *  progress / quit), add it to ALLOWED_FOLDERS and deploy again.
 *
 *  Protocol reference: receivers/README.md and docs/DATA_FORMAT.md
 *  ("Folders and file names").
 * ============================================================================
 */
"use strict";

const { app } = require("@azure/functions");
const { BlobServiceClient } = require("@azure/storage-blob");

// ── EDIT HERE (rarely needed) ───────────────────────────────────────────────

// Largest file accepted, in bytes. A full participant file is normally well
// under 2 MB; 10 MB leaves plenty of room.
const MAX_BYTES = 10 * 1024 * 1024;

// The only folders the experiment writes to (see docs/DATA_FORMAT.md).
const ALLOWED_FOLDERS = ["complete", "progress", "quit"];

// Allowed file names: letters, digits, "_", "-" and "." only, must end in
// ".json", at most ~200 characters, no slashes (so nothing can be written
// outside the folder) and no ".." (checked separately below). Matches e.g.
//   P3K9X2QA__AB12CD34.json
//   P3K9X2QA__AB12CD34__p03_stroop-baseline.json
//   5f01abc_2___AB12CD34__quit_7.json
const FILE_NAME_RE = /^[A-Za-z0-9_-][A-Za-z0-9_.-]{0,199}\.json$/;

// Container (top-level "folder") in the storage account.
const CONTAINER_NAME = process.env.CONTAINER_NAME || "participant-data";

// ── END OF EDIT HERE ────────────────────────────────────────────────────────

// Sent with every answer so the browser may read it (CORS).
const CORS_HEADERS = { "Access-Control-Allow-Origin": "*" };

// Build an answer: status code + small JSON body + CORS header.
function reply(status, body) {
  return {
    status,
    headers: { ...CORS_HEADERS, "Content-Type": "application/json" },
    jsonBody: body,
  };
}

// Which storage account to write to (see SETTINGS at the top).
function storageConnectionString() {
  const own = process.env.DATA_STORAGE_CONNECTION;
  if (own && own.trim()) return own.trim();
  // Fall back to the Function App's own storage, but only if it is a classic
  // connection string (newer apps may use an identity instead, which this
  // simple function does not support — then set DATA_STORAGE_CONNECTION).
  const host = process.env.AzureWebJobsStorage || "";
  if (/AccountKey=|SharedAccessSignature=|UseDevelopmentStorage=true/i.test(host)) return host;
  return "";
}

// Connect to the container once per running instance and reuse it.
let containerPromise = null;
function getContainer(context) {
  if (!containerPromise) {
    containerPromise = (async () => {
      const cs = storageConnectionString();
      if (!cs) {
        throw new Error(
          "No storage connection string. In the Function App, add the app setting " +
          "DATA_STORAGE_CONNECTION (Storage account → Access keys → Connection string)."
        );
      }
      const container = BlobServiceClient.fromConnectionString(cs).getContainerClient(CONTAINER_NAME);
      try {
        await container.createIfNotExists();   // first run only; harmless afterwards
      } catch (err) {
        // e.g. the key is not allowed to create containers: then create the
        // container by hand in the Portal. Saving below reports the real error.
        context.warn(`Could not check/create container "${CONTAINER_NAME}": ${err.message}`);
      }
      return container;
    })().catch((err) => {
      containerPromise = null;  // try again on the next request
      throw err;
    });
  }
  return containerPromise;
}

// ── The function itself ─────────────────────────────────────────────────────
async function save(request, context) {
  // Browsers never need this for our uploads (they are "simple requests"),
  // but answer a CORS pre-check politely just in case.
  if (request.method === "OPTIONS") {
    return {
      status: 204,
      headers: {
        ...CORS_HEADERS,
        "Access-Control-Allow-Methods": "POST, OPTIONS",
        "Access-Control-Allow-Headers": "Content-Type",
        "Access-Control-Max-Age": "86400",
      },
    };
  }

  // 1. Size check before reading (if the browser told us the size).
  const declared = Number(request.headers.get("content-length") || 0);
  if (declared > MAX_BYTES) {
    context.warn(`Rejected: body too large (${declared} bytes)`);
    return reply(413, { ok: false, error: "too_large", max_bytes: MAX_BYTES });
  }

  // 2. Read the body as text (the browser sends Content-Type text/plain).
  let text;
  try {
    text = await request.text();
  } catch (err) {
    return reply(400, { ok: false, error: "unreadable_body" });
  }
  const bytes = Buffer.byteLength(text, "utf8");
  if (bytes === 0) return reply(400, { ok: false, error: "empty_body" });
  if (bytes > MAX_BYTES) {
    context.warn(`Rejected: body too large (${bytes} bytes)`);
    return reply(413, { ok: false, error: "too_large", max_bytes: MAX_BYTES });
  }

  // 3. It must be JSON with a valid "upload" section.
  let data;
  try {
    data = JSON.parse(text);
  } catch (err) {
    return reply(400, { ok: false, error: "not_json" });
  }
  const upload = data && typeof data === "object" ? data.upload : null;
  if (!upload || typeof upload !== "object") {
    return reply(400, { ok: false, error: "missing_upload_section" });
  }
  const folder = String(upload.folder || "");
  const fileName = String(upload.file_name || "");
  if (!ALLOWED_FOLDERS.includes(folder)) {
    return reply(400, { ok: false, error: "bad_folder", allowed: ALLOWED_FOLDERS });
  }
  if (!FILE_NAME_RE.test(fileName) || fileName.includes("..")) {
    return reply(400, { ok: false, error: "bad_file_name" });
  }
  const blobPath = `${folder}/${fileName}`;

  // 4. Save the text unchanged — but only if no file with this name exists.
  try {
    const container = await getContainer(context);
    const blob = container.getBlockBlobClient(blobPath);
    const content = Buffer.from(text, "utf8");
    await blob.upload(content, content.length, {
      blobHTTPHeaders: { blobContentType: "application/json; charset=utf-8" },
      conditions: { ifNoneMatch: "*" },   // "*" = refuse if the blob already exists
    });
  } catch (err) {
    const status = err && err.statusCode;
    const code = err && err.code;
    // Already there: an earlier try of this same upload succeeded.
    // Storage answers an existing blob with 409 "BlobAlreadyExists" (seen with
    // the Azurite emulator) or, per the REST docs, 412 "ConditionNotMet".
    // Other 409s (e.g. "ContainerBeingDeleted") mean the file was NOT saved,
    // so they must not be reported as "already saved": they fall through to 500.
    if (code === "BlobAlreadyExists" || code === "ConditionNotMet" || status === 412) {
      context.log(`Already saved: ${blobPath}`);
      return reply(409, { ok: false, error: "already_exists", path: blobPath });
    }
    // Anything else is a real problem: log it (visible under the function's
    // "Invocations"/"Logs" in the Portal) and let the browser retry.
    context.error(`Saving ${blobPath} failed: ${status || ""} ${code || ""} ${err && err.message}`);
    return reply(500, { ok: false, error: "storage_error" });
  }

  // Never log the file contents (participant data) — only where it went.
  context.log(`Saved ${blobPath} (${bytes} bytes)`);
  return reply(200, { ok: true, path: blobPath, bytes });
}

// Register the function: URL  https://<your-app>/api/save?code=<function key>
//   methods   POST (uploads) and OPTIONS (CORS pre-check, see above)
//   authLevel "function" = the URL only works with the ?code=... key, which
//             you copy from the Portal ("Get function URL") into js/config.js.
app.http("save", {
  methods: ["POST", "OPTIONS"],
  authLevel: "function",
  route: "save",
  handler: save,
});

// Exported only so the function can be tested outside Azure; Azure ignores it.
module.exports = { save, FILE_NAME_RE, ALLOWED_FOLDERS };
